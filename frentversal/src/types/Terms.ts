/*
  회원가입 약관 동의 항목과 약관 전문.

  Navigation.ts가 메뉴 구성을 데이터로 들고 있는 것과 같은 방식으로,
  약관도 화면 코드(JSX)에 흩어 두지 않고 여기 한곳에 모았다.
  회원가입 화면(TermsAgreement)과 약관 전문 화면(TermsPage)이 같은 배열을 읽는다.

  약관 본문을 DB가 아니라 코드에 두는 이유:
  약관은 "언제 어떤 내용이 시행 중이었는가"가 중요한 문서라서, 배포 이력과 함께
  git에 남는 편이 관리하기 쉽다. DB에는 나중에 "누가 어느 버전에 동의했는지"만 남기면 된다.

  본문은 공정거래위원회 전자상거래(사이버몰) 표준약관과
  방송통신위원회 위치기반서비스 표준약관을 부동산 중개 플랫폼에 맞게 고쳐 쓴 것이다.
  실제 서비스로 열기 전에는 법률 검토를 한 번 받아야 한다.
*/

import type { SignupType } from './Auth';

// 동의 항목을 구분하는 코드. 나중에 DB에 저장하게 되면 이 값이 그대로 키가 된다.
export type AgreementCode =
    | 'service'      // 서비스 이용약관
    | 'privacy'      // 개인정보 수집·이용 동의
    | 'age'          // 만 14세 이상 확인
    | 'location'     // 위치기반서비스 이용약관
    | 'thirdParty'   // 개인정보 제3자 제공 동의 (사용자 → 중개인)
    | 'agencyPublic' // 중개사무소 정보 공개 동의 (중개인)
    | 'marketing';   // 마케팅 정보 수신 동의

// 약관 본문 한 덩어리. 표로 보여줘야 하는 항목(수집·이용 동의 등)은 table을 쓴다.
export type TermsSection = {
    heading?: string;
    paragraphs?: string[];
    table?: {
        head: string[];
        rows: string[][];
    };
};

export type TermsDoc = {
    code: AgreementCode;
    // 체크박스 옆에 나오는 짧은 이름
    title: string;
    version: string;
    // 시행일. 약관이 바뀌면 version과 함께 올린다.
    effectiveDate: string;
    // 이 가입 유형에게 항목을 보여줄지
    showFor: SignupType[];
    // 이 가입 유형에게 필수인지. 비어 있으면 선택 항목이다.
    requiredFor: SignupType[];
    // 체크박스 아래 한 줄 안내
    summary: string;
    sections: TermsSection[];
};

