// 체크 상태를 담는 모양. 항목 코드 → 동의 여부
export type AgreementState = Partial<Record<AgreementCode, boolean>>;

// 가입 유형에 해당하는 약관만 고른다.
export function termsFor(signupType: SignupType): TermsDoc[] {
    return TERMS_DOCS.filter((doc) => doc.showFor.includes(signupType));
}

export function isRequired(doc: TermsDoc, signupType: SignupType): boolean {
    return doc.requiredFor.includes(signupType);
}

// 아직 동의하지 않은 필수 항목. 비어 있으면 가입을 진행해도 된다.
export function missingRequired(signupType: SignupType, agreed: AgreementState): TermsDoc[] {
    return termsFor(signupType).filter((doc) => isRequired(doc, signupType) && !agreed[doc.code]);
}

// 코드로 약관 하나를 찾는다. 약관 전문 화면(/terms/:code)에서 쓴다.
export function findTerms(code: string | undefined): TermsDoc | undefined {
    return TERMS_DOCS.find((doc) => doc.code === code);
}
